package entity;

import java.time.Duration;
import java.time.LocalDateTime;

public abstract class TimeBlock {

    private final String id;
    private final String title;
    private final String description; // "" if none
    private final LocalDateTime start;
    private final LocalDateTime end;

    // protected: only subclasses can call this

    protected TimeBlock(String id, String title, String description, LocalDateTime start, LocalDateTime end) {
        if (id == null) {
            throw new IllegalArgumentException("Block id is required");
        }
        if (title == null) {
            throw new IllegalArgumentException("Title cannot be empty");
        }
        if (start == null || end == null) {
            throw new IllegalArgumentException("Start and end times are required");
        }
        if (!end.isAfter(start)) {
            throw new IllegalArgumentException("End time must be after start time");
        }

        this.id = id;
        this.title = title;
        this.start = start;
        this.end = end;
        if (description == null) {
            this.description = "";
        } else {
            this.description = description.strip();
        }
    }

    // Checks if this is a fixed commitment the scheduler has to plan around. Events are fixed (true); FocusBlocks generated by scheduler (false)
    // Student can still edit either type in use case 4
    public abstract boolean isFixed();

    // Returns whether two TimeBlock objects overlap
    public boolean overlaps(LocalDateTime otherStart, LocalDateTime otherEnd) {
        return start.isBefore(otherEnd) && otherStart.isBefore(end);
    }

    // True if this block ends at or before other starts
    public boolean isBeforeUnstrict(TimeBlock other) {
        return !end.isAfter(other.getStart());
    }

    // True if this block starts at or after other ends
    public boolean isAfterUnstrict(TimeBlock other) {
        return !start.isBefore(other.getEnd());
    }

    // True if this block ends before other starts
    public boolean isBefore(TimeBlock other) {
        return end.isBefore(other.getStart());
    }

    // True if this block starts before other ends
    public boolean isAfter(TimeBlock other) {
        return start.isAfter(other.getEnd());
    }

    // Returns whether two TimeBlock objects overlap
    public boolean overlaps(TimeBlock other) {
        return overlaps(other.getStart(), other.getEnd());
    }

    // Returns the duration of a TimeBlock object from start to end
    // Type long is type int but can hold much larger numbers
    public long getDurationMinutes() {
        return Duration.between(start, end).toMinutes();
    }

    // getters
    public String getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public String getDescription() {
        return description;
    }

    public LocalDateTime getStart() {
        return start;
    }

    public LocalDateTime getEnd() {
        return end;
    }
}
